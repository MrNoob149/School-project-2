CREATE TABLE IF NOT EXISTS `project` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `Title` VARCHAR(255) NOT NULL,
    `Description` LONGTEXT NOT NULL,
    `CreatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UpdatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`)
);


CREATE TABLE IF NOT EXISTS `User` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `First_Name` VARCHAR(255) NOT NULL,
    `Last_Name` VARCHAR(255) NOT NULL,
    `Email` VARCHAR(255) NOT NULL UNIQUE,
    `Password` VARCHAR(255) NOT NULL,
    PRIMARY KEY (`id`)
);


CREATE TABLE IF NOT EXISTS `UserProjects` (
    `Users_ID` INT UNSIGNED NOT NULL,
    `Projects_ID` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`Users_ID`, `Projects_ID`)
);


CREATE TABLE IF NOT EXISTS `Video` (
    `id` INT UNSIGNED NOT NULL,
    `URL` VARCHAR(2048) NOT NULL,
    `video_length` INT NOT NULL,
    `resolution` VARCHAR(50) NOT NULL,
    `code` VARCHAR(255) NOT NULL,
    PRIMARY KEY (`id`)
);


CREATE TABLE IF NOT EXISTS `Media` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `Project_ID` INT UNSIGNED NOT NULL,
    `Type` ENUM('video', 'image', 'flipbook') NOT NULL,
    PRIMARY KEY (`id`)
);


CREATE TABLE IF NOT EXISTS `ProjectTags` (
    `project_id` INT UNSIGNED NOT NULL,
    `Tags_id` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`project_id`, `Tags_id`)
);


CREATE TABLE IF NOT EXISTS `user_roles` (
    `user_id` INT UNSIGNED NOT NULL,
    `roles_id` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`user_id`, `roles_id`)
);


CREATE TABLE IF NOT EXISTS `Tags` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `title` VARCHAR(255) NOT NULL,
    `description` TEXT NOT NULL,
    PRIMARY KEY (`id`)
);


CREATE TABLE IF NOT EXISTS `roles` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `name` VARCHAR(255) NOT NULL,
    `active` TINYINT NOT NULL DEFAULT 1,
    `slug` VARCHAR(255) NOT NULL,
    `CreatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UpdatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    `Content` TEXT,
    PRIMARY KEY (`id`),
    UNIQUE (`slug`)
);


CREATE TABLE IF NOT EXISTS `permission` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `name` VARCHAR(255) NOT NULL,
    `slug` VARCHAR(255) NOT NULL,
    `description` TEXT NOT NULL,
    `Active` TINYINT NOT NULL DEFAULT 1,
    `CreatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `DeactivateAt` DATETIME NULL,
    `Content` TEXT,
    PRIMARY KEY (`id`),
    UNIQUE (`slug`)
);


CREATE TABLE IF NOT EXISTS `roles_permission` (
    `permission_id` INT UNSIGNED NOT NULL,
    `roles_id` INT UNSIGNED NOT NULL,
    `CreatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UpdatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`permission_id`, `roles_id`)
);


CREATE TABLE IF NOT EXISTS `Image` (
    `id` INT UNSIGNED NOT NULL,
    `URL` VARCHAR(2048) NOT NULL,
    `resolution` VARCHAR(50) NOT NULL,
    PRIMARY KEY (`id`)
);


CREATE TABLE IF NOT EXISTS `Flipbook` (
    `id` INT UNSIGNED NOT NULL,
    `PageCount` INT NOT NULL,
    PRIMARY KEY (`id`)
);


