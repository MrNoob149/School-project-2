CREATE TABLE IF NOT EXISTS `project` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Title` VARCHAR(255) NOT NULL,
	`Description` LONGTEXT(65535) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `User` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`First_Name` VARCHAR(255) NOT NULL,
	`Last_Name` VARCHAR(255) NOT NULL,
	`Email` VARCHAR(255) NOT NULL UNIQUE,
	`Password` VARCHAR(255) NOT NULL UNIQUE,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `UserProjects` (
	`Users_ID` INTEGER NOT NULL,
	`Projects_ID` INTEGER NOT NULL
);


CREATE TABLE IF NOT EXISTS `Video` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`URL` TEXT(65535) NOT NULL,
	`video.length` INTEGER NOT NULL,
	`resolution` SMALLINT NOT NULL,
	`code` VARCHAR(255) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Media` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`Project_ID` INTEGER NOT NULL,
	`Type` INTEGER NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `ProjectTags` (
	`project_id` INTEGER NOT NULL,
	`Tags_id` INTEGER NOT NULL
);


CREATE TABLE IF NOT EXISTS `user_roles` (
	`user_id` INTEGER NOT NULL,
	`roles_id` INTEGER NOT NULL
);


CREATE TABLE IF NOT EXISTS `Tags` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`title` VARCHAR(255) NOT NULL,
	`description` TEXT(65535) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `roles` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`name` VARCHAR(255) NOT NULL,
	`active` SMALLINT NOT NULL,
	`slug` VARCHAR(255) NOT NULL,
	`CreatedAt` DATETIME NOT NULL,
	`UpdatedAt` DATETIME NOT NULL,
	`Content` TEXT(65535)
);


CREATE TABLE IF NOT EXISTS `permission` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`name` VARCHAR(255) NOT NULL,
	`slug` VARCHAR(255) NOT NULL,
	`description` TEXT(65535) NOT NULL,
	`Active` TINYINT NOT NULL,
	`CreatedAt` DATETIME NOT NULL,
	`DeactivateAt` DATETIME NOT NULL,
	`Content` TEXT(65535),
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `roles_permission` (
	`permission_id` INTEGER NOT NULL,
	`roles_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`CreatedAt` DATETIME NOT NULL,
	`UpdatedAt` DATETIME NOT NULL
);


CREATE TABLE IF NOT EXISTS `Image` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`URL` VARCHAR(255) NOT NULL,
	`resolution` TEXT(65535) NOT NULL,
	PRIMARY KEY(`id`)
);


CREATE TABLE IF NOT EXISTS `Flipbook` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`PageCount` INTEGER NOT NULL,
	PRIMARY KEY(`id`)
);


